/**
 * Д2: определение режима — блокирующий код, отмена корутины его не прерывает, и отменённый замер доходит до конца. Каждый запуск берёт
 * порядковый номер; результат записывает только последний запущенный, иначе два замера дают два голоса «подряд» (находка 3.3).
 */
object DetectSeq {
    fun isLatest(my: Long, current: Long): Boolean = my == current
}
