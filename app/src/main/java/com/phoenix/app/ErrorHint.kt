package com.phoenix.app

/** Ошибки по образцу «что случилось → что сделать»: к техническому тексту службы добавляется действие, если оно известно. */
object ErrorHint {
    /** null — подсказки нет. Ключи сравниваются по началу русского текста ошибки (до подстановки языка). */
    fun key(error: String): String? {
        val e = error.lowercase()
        return when {
            e.startsWith("нет конфига") || e.startsWith("no config") -> "Нет серверов → соберите их: меню ⋮ → «Собрать сейчас»"
            e.startsWith("система не разрешила") -> "Нет разрешения VPN → откройте приложение и нажмите на круг"
            e.startsWith("ошибка запуска") -> "Не запустилось → нажмите на круг ещё раз или выберите другой сервер"
            else -> null
        }
    }
}
