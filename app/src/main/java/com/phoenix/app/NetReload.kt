package com.phoenix.app

/**
 * Нужно ли после смены сети пересоздавать сокеты ядра (С2). Проверка связи идёт до 15 секунд, потом обработчик ждёт общий замок
 * смены сервера/режима; за это время ядро могли уже перезапустить на другом сервере (журнал 24.11: «переключился на запасной [Finland]»
 * и в ту же секунду «пересоздал сокеты ядра тем же сервером [Finland]»). Тогда сокеты новые, лишний перезапуск — секунды без связи.
 */
object NetReload {
    /** [genBefore] — номер поколения ядра до проверки связи, [genNow] — под замком; нужно, только если ядро то же и связи нет. */
    fun needed(genBefore: Int, genNow: Int, healthy: Boolean): Boolean = genBefore == genNow && !healthy
}
