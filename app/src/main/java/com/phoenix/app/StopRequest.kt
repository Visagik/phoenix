package com.phoenix.app

import kotlinx.coroutines.flow.MutableStateFlow

/**
 * Кнопка «Остановить и сохранить» на главной. Перепроверка, проверка приложений и подбор для целей сами смотрят сюда и
 * заканчивают работу: уже полученные результаты записаны (они сохраняются по ходу), дальше ничего не запускается.
 * Запрос действует на то, что началось раньше него, и на продолжение цепочки: сбор → перепроверка → подбор серверов для целей запускаются
 * один за другим, и нажатие во время сбора раньше не доходило до следующих этапов (они стартовали «позже нажатия»: журнал 22.11, подбор для
 * целей шёл дальше). Этап, начавшийся не позже [CHAIN_MS] после нажатия, считается продолжением. Новая работа, запущенная вручную, запрос
 * снимает ([clear]) и не отменяется.
 */
object StopRequest {
    /** Время последнего нажатия, 0 — не нажимали. Для интерфейса («Останавливаю…»). */
    val at = MutableStateFlow(0L)

    fun request(now: Long = System.currentTimeMillis()) { at.value = now }

    /** Нажимали ли «Остановить» после начала работы [startedAt]. */
    fun requestedSince(startedAt: Long): Boolean {
        val a = at.value
        return a > 0 && (a >= startedAt || startedAt - a <= CHAIN_MS)
    }

    /** Следующий этап цепочки может начаться не сразу (подбор для целей ставится в очередь после перепроверки). */
    const val CHAIN_MS = 5 * 60_000L

    /** Работа запущена вручную: прежняя просьба остановиться к ней не относится. */
    fun clear() { at.value = 0L }

    /** Для показа в интерфейсе: остановка запрошена, а работа ещё идёт (идёт с [startedAt] или позже неизвестно — берём окно в 2 минуты). */
    fun pending(now: Long = System.currentTimeMillis()): Boolean = at.value > 0 && now - at.value < 120_000
}
