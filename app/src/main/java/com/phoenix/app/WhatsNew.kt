package com.phoenix.app

/**
 * «Что нового»: короткие пункты для пользователя по версиям (не весь CHANGELOG). Новая версия добавляется первой строкой списка.
 * Окно после обновления показывается один раз; список по всем версиям — в «Ещё → Что нового». Каждый пункт переводится через tr().
 */
object WhatsNew {
    data class Entry(val version: String, val items: List<String>)

    /** Новые версии сверху. Пункты — русские ключи переводов (addkeys.py). */
    val ENTRIES: List<Entry> = listOf(
        Entry("3.9.67", listOf(
            "Если обновление подписано другим ключом, приложение сохранит копию настроек и скачает новую версию, а переустановить её нужно самому.",
            "Меньше простоя при сбоях: смена сервера ограничена по времени, а после смены сети и «дёрганья» Wi-Fi сервер не винится зря.",
            "Знакомые сети запоминаются: в известном Wi-Fi или у оператора режим блокировок берётся сразу, без ожидания замера.",
            "На слабых телефонах при нехватке памяти проверок идёт меньше, чтобы систему не убила приложение.",
            "Новое обучение и раздел «Ещё → Фишки»: плитки, виджет, ярлыки, свой сервер для приложений.",
            "«Режим блокировок» показывает свежий результат со временем, сеть пишется как «Wi-Fi».",
            "Тип блокировок определяется сразу после запуска, а Wi-Fi без интернета больше не переключает режим туда-сюда.",
            "Бегущая строка с фактами о Phoenix на главном экране: выключена, включается в «Ещё → Фишки».",
        )),
        Entry("3.9.66", listOf(
            "Кнопка «Остановить и сохранить» и подробности перепроверки на главной.",
            "Перепроверка быстрее: мёртвые серверы не ждёт заново; есть настройка «Скорость перепроверки».",
            "При смене сервера под открытое приложение сначала проверяются подходящие серверы.",
            "Notebook больше не ставит ✓ на закрытых серверах, «Не работает» снимает галочку.",
