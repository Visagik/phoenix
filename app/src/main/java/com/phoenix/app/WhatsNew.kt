    private fun norm(v: String) = v.trim().removePrefix("v").removePrefix("V")

    fun forVersion(version: String): Entry? = ENTRIES.firstOrNull { norm(it.version) == norm(version) }

    /**
     * Показать окно после обновления: для текущей версии есть пункты, пользователь их ещё не видел ([seen] пусто — не видел ни одной,
     * это тот, кто обновился до появления окна) и версия не старее виденной (откат на старую сборку окно не открывает).
     * Новая установка ([fresh]) проходит обучение и окна не получает.
     */
    fun shouldShow(seen: String, current: String, fresh: Boolean): Boolean =
        !fresh && forVersion(current) != null && norm(seen) != norm(current) && (seen.isBlank() || UpdateCheck.isNewer(current, seen))
